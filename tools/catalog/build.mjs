#!/usr/bin/env node
// Build the scorecard catalogue from the Governance House site data + the assessment overlay.
// The site is the source of truth for rooms and checks; this script fails if the overlay and
// the site disagree, so the talk and the skill cannot drift apart.
//
//   node tools/catalog/build.mjs           write the catalogue
//   node tools/catalog/build.mjs --check   exit 1 if the committed catalogue is stale

import { createHash } from "node:crypto";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join, relative, resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { rooms } from "../../sites/governance-house/src/data/rooms.js";
import {
  GOVERNANCE_REVIEWED,
  GOVERNANCE_SCOPE,
  governancePrinciples,
  governanceSources,
  roomGovernance,
  widerGovernance,
} from "../../sites/governance-house/src/data/governance.js";
import { consequentialPatterns, discoveryConcepts, frameworkPatterns, signals, toolPatterns } from "./signals.mjs";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "../..");
const skillRefs = join(repoRoot, "skills/agent-governance-scorecard/references");
const ADOPTION_ORDER = ["identity", "ledger", "shutdown", "permission", "uncertainty", "reliability"];

function buildCatalog() {
  const problems = [];
  const seen = new Set();

  const catalogRooms = rooms.map((room) => ({
    id: room.id,
    number: room.number,
    title: room.title,
    short: room.short,
    practice: room.principle,
    question: room.question,
    accent: room.accent,
    summary: room.summary,
    risks: room.risks,
    limitation: room.limitation,
    governance: roomGovernance[room.id],
    checks: room.checks.map((check) => {
      const id = `${room.id}/${check.id}`;
      seen.add(id);
      const overlay = signals[id];
      if (!overlay) problems.push(`No signals for ${id} — add it to tools/catalog/signals.mjs`);
      return {
        id,
        room: room.id,
        title: check.title,
        action: check.action,
        verify: check.verify,
        priority: room.priorityChecks.includes(check.id),
        ...overlay,
      };
    }),
  }));

  for (const id of Object.keys(signals)) {
    if (!seen.has(id)) problems.push(`signals.mjs has ${id}, which is not a check on the site`);
  }
  for (const room of catalogRooms) {
    if (!ADOPTION_ORDER.includes(room.id)) problems.push(`Room ${room.id} is missing from ADOPTION_ORDER`);
  }
  if (problems.length) {
    console.error(problems.map((p) => `✗ ${p}`).join("\n"));
    process.exit(1);
  }

  const body = {
    reviewed: GOVERNANCE_REVIEWED,
    scope: GOVERNANCE_SCOPE,
    storyOrder: catalogRooms.map((room) => room.id),
    adoptionOrder: ADOPTION_ORDER,
    statuses: {
      present: "Implemented and backed by evidence in the codebase.",
      partial: "Some of the control exists, but part of the action or its enforcement is missing.",
      missing: "No implementation found.",
      not_applicable: "Does not apply to this agent (a reason is required).",
      unknown: "Cannot be decided from the code alone; needs an answer from the team.",
    },
    principles: governancePrinciples,
    sources: governanceSources,
    widerGovernance,
    rooms: catalogRooms,
    discovery: { concepts: discoveryConcepts, consequentialPatterns, toolPatterns, frameworkPatterns },
  };
  const version = createHash("sha256").update(JSON.stringify(body)).digest("hex").slice(0, 12);
  return { catalogVersion: version, generatedFrom: "sites/governance-house/src/data + tools/catalog/signals.mjs", ...body };
}

function roomMarkdown(room, catalog) {
  const principle = (key) => catalog.principles[key]?.name ?? key;
  const lines = [
    `<!-- Generated by tools/catalog/build.mjs from the Governance House site data. Do not edit by hand. -->`,
    `# ${room.number} · ${room.short} — ${room.title}`,
    "",
    `**Question:** ${room.question}`,
    "",
    room.summary,
    "",
    `**Risks it addresses:** ${room.risks.join("; ")}.`,
    "",
    "## Checks",
    "",
    "Priority checks (★) carry double weight in the score.",
    "",
  ];
  for (const check of room.checks) {
    lines.push(
      `### ${check.priority ? "★ " : ""}\`${check.id}\` — ${check.title}`,
      "",
      `- **Action (what good looks like):** ${check.action}`,
      `- **Verify (the behavioural test):** ${check.verify}`,
      `- **Provable from:** \`${check.provable}\``,
      `- **Evidence to look for:**`,
      ...check.lookFor.map((item) => `  - ${item}`),
      `- **Does not count on its own:**`,
      ...check.notEnough.map((item) => `  - ${item}`),
      `- **Typical fix:** ${check.fix}`,
      "",
    );
  }
  lines.push(
    "## Honest limitation",
    "",
    `**${room.limitation.title}** ${room.limitation.body}`,
    "",
    "Companion rooms:",
    ...room.limitation.companions.map((c) => `- **${c.roomId}** — ${c.reason}`),
    "",
    "## Principles it supports",
    "",
    `_${room.governance.headline}_`,
    "",
    ...room.governance.mappings.map((m) => `- **${principle(m.principle)}:** ${m.contribution}`),
    "",
    `Still required: ${room.governance.remaining}`,
    "",
  );
  return lines.join("\n");
}

const catalog = buildCatalog();
const outputs = new Map([[join(skillRefs, "catalog.json"), `${JSON.stringify(catalog, null, 2)}\n`]]);
for (const room of catalog.rooms) {
  outputs.set(join(skillRefs, "rooms", `${room.number}-${room.id}.md`), roomMarkdown(room, catalog));
}

if (process.argv.includes("--check")) {
  const stale = [];
  for (const [path, content] of outputs) {
    const current = await readFile(path, "utf8").catch(() => null);
    if (current !== content) stale.push(relative(repoRoot, path));
  }
  if (stale.length) {
    console.error(`✗ Catalogue is stale. Run \`npm run build:catalog\`.\n  ${stale.join("\n  ")}`);
    process.exit(1);
  }
  console.log(`✓ Catalogue ${catalog.catalogVersion} is up to date.`);
} else {
  await rm(join(skillRefs, "rooms"), { recursive: true, force: true });
  await mkdir(join(skillRefs, "rooms"), { recursive: true });
  for (const [path, content] of outputs) await writeFile(path, content);
  const checks = catalog.rooms.reduce((n, room) => n + room.checks.length, 0);
  console.log(`✓ Catalogue ${catalog.catalogVersion}: ${catalog.rooms.length} rooms, ${checks} checks → ${relative(repoRoot, skillRefs)}`);
}
